describe("public action contracts", () => {
	it("covers every published action", async () => {
		// Arrange
		const published = glob("actions/**/action.yml", { cwd: root });
		// Act
		const paths = [];
		for await (const path of published)
			paths.push(path.replace("/action.yml", ""));
		// Assert
		expect(paths.sort()).toEqual(
			[
				...actionContracts.map((item) => item.directory),
				"actions/publication/reconcile-event",
				"actions/referential/reconcile-speakers",
			].sort(),
		);
	});
	it("keeps release-generated references identifiable", async () => {
		// Arrange
		const references = glob("actions/**/README.md", { cwd: root });
		// Act
		const documents = [];
		for await (const path of references)
			documents.push(await readFile(join(root, path), "utf8"));
		// Assert
		expect(documents.length).toBeGreaterThan(0);
		for (const document of documents)
			expect(document).toContain(
				"This documentation was automatically generated by [CI Dokumentor]",
			);
	});
	it.each(actionContracts)(
		"publishes the exact metadata contract and bundle for $directory",
		async ({ directory, inputs, outputs }) => {
			// Arrange
			const bundlePath = join(root, directory, "dist/index.js");

			// Act
			const manifest = await readYaml<ActionManifest>(
				join(directory, "action.yml"),
			);
			const bundleAccess = await access(bundlePath);

			// Assert
			expect(manifest.runs).toMatchObject({
				main: "dist/index.js",
				using: "node24",
			});
			expect(sortedKeys(manifest.inputs)).toEqual([...inputs, "locale"].sort());
			expect(sortedKeys(manifest.outputs)).toEqual([...outputs].sort());
			expect(bundleAccess).toBeUndefined();
		},
	);

	it.each(["issue-form/reconcile"])(
		"requires an explicit mode for %s",
		async (action) => {
			// Arrange
			const actionPath = `actions/${action}/action.yml`;

			// Act
			const manifest = await readYaml<ActionManifest>(actionPath);

			// Assert
			expect(manifest.inputs?.mode?.required).toBe(true);
			expect(manifest.inputs?.mode?.default).toBeUndefined();
		},
	);

	it.each(["openfeedback-api-key"])(
		"requires an explicit %s for feedback reconciliation",
		async (inputName) => {
			// Arrange
			const actionPath = "actions/feedback/reconcile-event/action.yml";

			// Act
			const manifest = await readYaml<ActionManifest>(actionPath);
			const input = manifest.inputs?.[inputName];

			// Assert
			expect(input?.required).toBe(true);
			expect(input?.default).toBeUndefined();
		},
	);

	it.each(["mailings-token", "slack-organizer-channel-id", "slack-token"])(
		"requires an explicit %s for communication reconciliation",
		async (inputName) => {
			// Arrange
			const actionPath = "actions/communication/reconcile-email/action.yml";

			// Act
			const manifest = await readYaml<ActionManifest>(actionPath);
			const input = manifest.inputs?.[inputName];

			// Assert
			expect(input?.required).toBe(true);
			expect(input?.default).toBeUndefined();
		},
	);

	it("requires a managed author only for communication and exposes no execution switches", async () => {
		// Arrange
		const event = await readYaml<ActionManifest>(
			"actions/event/reconcile/action.yml",
		);

		// Act
		const communication = await readYaml<ActionManifest>(
			"actions/communication/reconcile-email/action.yml",
		);

		// Assert
		expect(event.inputs).not.toHaveProperty("managed-comment-author");
		expect(communication.inputs?.["managed-comment-author"]?.required).toBe(
			true,
		);
		expect(communication.inputs).not.toHaveProperty("mode");
		expect(communication.inputs).not.toHaveProperty("dispatch-authorized");
		expect(communication.inputs).not.toHaveProperty("slack-channel-id");
	});
});
