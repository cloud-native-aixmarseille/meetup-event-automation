import { access, readFile } from "node:fs/promises";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { type ActionManifest, readYaml, root, sortedKeys } from "./support.js";

const actionContracts = [
	{
		directory: "actions/communication/reconcile-attention",
		inputs: [
			"asset-folder-url-prefix",
			"community-event-url-prefixes",
			"meetup-event-url-prefix",
			"github-token",
			"issue-number",
			"managed-comment-author",
			"slack-organizer-channel-id",
			"slack-token",
			"stage-results",
		],
		outputs: [],
	},
	{
		directory: "actions/publication/reconcile-feedback",
		inputs: [
			"asset-folder-url-prefix",
			"community-event-url-prefixes",
			"meetup-event-url-prefix",
			"conference-hall-api-key",
			"conference-hall-event",
			"github-token",
			"issue-number",
			"kutt-api-key",
			"kutt-base-url",
			"kutt-link-id",
			"openfeedback-api-key",
		],
		outputs: ["diagnostics"],
	},
	{
		directory: "actions/publication/reconcile-assets",
		inputs: [
			"asset-folder-url-prefix",
			"community-event-url-prefixes",
			"meetup-event-url-prefix",
			"conference-hall-api-key",
			"conference-hall-event",
			"github-token",
			"google-credentials",
			"google-drive-folder-id",
			"google-drive-public-folder-id",
			"google-drive-template-folder-id",
			"issue-number",
		],
		outputs: ["drive-files", "slides-ready", "diagnostics"],
	},
	{
		directory: "actions/event/reconcile",
		inputs: [
			"asset-folder-url-prefix",
			"community-event-url-prefixes",
			"meetup-event-url-prefix",
			"conference-hall-api-key",
			"conference-hall-event",
			"github-token",
			"issue-number",
		],
		outputs: ["diagnostics"],
	},
	{
		directory: "actions/event/list-active",
		inputs: ["github-token"],
		outputs: ["issue-numbers"],
	},
	{
		directory: "actions/referential/validate",
		inputs: [],
		outputs: [],
	},
	{
		directory: "actions/referential/sync-issue-form",
		inputs: ["mode"],
		outputs: ["changed"],
	},
	{
		directory: "actions/communication/reconcile",
		inputs: [
			"asset-folder-url-prefix",
			"community-event-url-prefixes",
			"meetup-event-url-prefix",
			"conference-hall-api-key",
			"conference-hall-event",
			"openfeedback-api-key",
			"slides-url",
			"slides-ready",
			"github-token",
			"issue-number",
			"mailings-token",
			"managed-comment-author",
			"slack-organizer-channel-id",
			"slack-token",
		],
		outputs: ["diagnostics"],
	},
] as const;

describe("public action contracts", () => {
	it.each(actionContracts)(
		"publishes the exact metadata contract and bundle for $directory",
		async ({ directory, inputs, outputs }) => {
			// Arrange
			const readmePath = join(root, directory, "README.md");

			// Act
			const manifest = await readYaml<ActionManifest>(
				join(directory, "action.yml"),
			);
			const readmeAccess = await access(readmePath);
			const documentation = await readFile(readmePath, "utf8");
			const bundleAccess = await access(join(root, directory, "dist/index.js"));

			// Assert
			expect(manifest.runs).toMatchObject({
				main: "dist/index.js",
				using: "node24",
			});
			expect(sortedKeys(manifest.inputs)).toEqual([...inputs, "locale"].sort());
			expect(sortedKeys(manifest.outputs)).toEqual([...outputs].sort());
			expect(readmeAccess).toBeUndefined();
			expect(documentation).toContain(
				"This documentation was automatically generated by [CI Dokumentor]",
			);
			expect(bundleAccess).toBeUndefined();
		},
	);

	it.each(["referential/sync-issue-form"])(
		"requires an explicit mode for %s",
		async (action) => {
			// Arrange
			const actionPath = `actions/${action}/action.yml`;

			// Act
			const manifest = await readYaml<ActionManifest>(actionPath);

			// Assert
			expect(manifest.inputs?.mode?.required).toBe(true);
			expect(manifest.inputs?.mode?.default).toBeUndefined();
		},
	);

	it.each([
		"openfeedback-api-key",
		"kutt-api-key",
		"kutt-base-url",
		"kutt-link-id",
	])(
		"requires an explicit %s for feedback reconciliation",
		async (inputName) => {
			// Arrange
			const actionPath = "actions/publication/reconcile-feedback/action.yml";

			// Act
			const manifest = await readYaml<ActionManifest>(actionPath);
			const input = manifest.inputs?.[inputName];

			// Assert
			expect(input?.required).toBe(true);
			expect(input?.default).toBeUndefined();
		},
	);

	it.each(["mailings-token", "slack-organizer-channel-id", "slack-token"])(
		"requires an explicit %s for communication reconciliation",
		async (inputName) => {
			// Arrange
			const actionPath = "actions/communication/reconcile/action.yml";

			// Act
			const manifest = await readYaml<ActionManifest>(actionPath);
			const input = manifest.inputs?.[inputName];

			// Assert
			expect(input?.required).toBe(true);
			expect(input?.default).toBeUndefined();
		},
	);

	it("requires a managed author only for communication and exposes no execution switches", async () => {
		// Arrange
		const event = await readYaml<ActionManifest>(
			"actions/event/reconcile/action.yml",
		);

		// Act
		const communication = await readYaml<ActionManifest>(
			"actions/communication/reconcile/action.yml",
		);

		// Assert
		expect(event.inputs).not.toHaveProperty("managed-comment-author");
		expect(communication.inputs?.["managed-comment-author"]?.required).toBe(
			true,
		);
		expect(communication.inputs).not.toHaveProperty("mode");
		expect(communication.inputs).not.toHaveProperty("dispatch-authorized");
		expect(communication.inputs).not.toHaveProperty("slack-channel-id");
	});
});
